# --- LECTOR DE IMAGENES ---
def maze_from_image(path_image: str = maze_image_path) -> list[list]:
    '''
    Cargar un maze a partir de una imagen png, con 32x32 pixeles.
    Donde el color negro se sustituya por 1, es muro.
    Y el color blanco se sustituya por 0, es camino.
    '''

    # Cargar la imagen y convertirla a escala de grises ('L')
    img = Image.open(path_image).convert('L')

    # Aseguramos el tamaño de 32x32 píxeles
    img = img.resize((32, 32), Image.Resampling.NEAREST)

    # Convertir a un array de datos
    pixels = np.array(img)

    # Generar la lista de listas (matriz)
    # Usamos un umbral de 128 para decidir si es negro (1) o blanco (0)
    maze = [[1 if pixels[y, x] < 128 else 0 for x in range(32)] for y in range(32)]

    # Devuleve la matriz resultante
    return maze

